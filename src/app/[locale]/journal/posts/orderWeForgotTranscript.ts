type Turn = { speaker: 'OTHER SPEAKER' | 'GURUDEV'; paragraphs: string[] }

function parseTranscript(raw: string): Turn[] {
  const turns: Turn[] = []
  let current: Turn | null = null
  for (const block of raw.trim().split(/\n\s*\n/)) {
    const t = block.trim()
    if (t === 'OTHER SPEAKER:' || t === 'GURUDEV:') {
      current = { speaker: t.slice(0, -1) as Turn['speaker'], paragraphs: [] }
      turns.push(current)
    } else if (current) {
      current.paragraphs.push(t)
    }
  }
  return turns
}


